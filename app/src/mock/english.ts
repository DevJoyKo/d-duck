const HANGUL = /[가-힣]/;

type Table = { exact: Map<string, string>; parts: Pair[]; patterns: [RegExp, string][] };

function table(pairs: Pair[], partsAllowed: boolean): Table {
  const exact = new Map<string, string>();
  const parts: Pair[] = [];
  const patterns: [RegExp, string][] = [];
  for (const [ko, en] of pairs) {
    if (ko.includes("{}")) {
      const src = ko.split("{}").map((s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("(.+?)");
      let i = 0;
      patterns.push([new RegExp(src, "g"), en.replace(/\{\}/g, () => `$${++i}`)]);
    } else {
      exact.set(ko, en);
      if (partsAllowed) parts.push([ko, en]);
    }
  }
  parts.sort((a, b) => b[0].length - a[0].length);
  return { exact, parts, patterns };
}

const BACK = table(BACKEND, false);
const BACK_PARTS = table(BACKEND_PARTS, true);
const DATA_T = table(DATA, true);
const REVERSE = new Map(DATA.filter(([ko]) => !ko.includes("{}")).map(([ko, en]) => [en, ko]));

function swap(s: string, t: Table): string {
  let out = s;
  for (const [re, en] of t.patterns) out = out.replace(re, en);
  for (const [ko, en] of t.parts) if (out.includes(ko)) out = out.split(ko).join(en);
  return out;
}

function text(s: string, backend: boolean, data: boolean): string {
  if (!HANGUL.test(s)) return s;
  if (data && DATA_T.exact.has(s)) return DATA_T.exact.get(s)!;
  if (backend && BACK.exact.has(s)) return BACK.exact.get(s)!;
  let out = s;
  if (backend) out = swap(out, BACK_PARTS);
  if (data) out = swap(out, DATA_T);
  return out;
}

function deep(v: unknown, f: (s: string) => string): unknown {
  if (typeof v === "string") return f(v);
  if (Array.isArray(v)) return v.map((x) => deep(x, f));
  if (v && typeof v === "object" && Object.getPrototypeOf(v) === Object.prototype) {
    return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, deep(x, f)]));
  }
  return v;
}

/** Mock output in the languages asked for: `backend` for i18n.rs sentences, `data` for the fake user content. */
export function localize<T>(v: T, backend: Lang, data: Lang): T {
  const b = backend === "en";
  const d = data === "en";
  if (!b && !d) return v;
  if (v instanceof Error) return new Error(text(v.message, b, d)) as T;
  return deep(v, (s) => text(s, b, d)) as T;
}

/** Arguments back to the Korean fixtures, so mock lookups by name or text still match (whole strings only). */
export function delocalize<T>(v: T, data: Lang): T {
  if (data !== "en") return v;
  return deep(v, (s) => REVERSE.get(s) ?? s) as T;
}
